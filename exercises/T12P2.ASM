title Programa para Matrices Tarea12
model small
stack 256
dataseg
exCode db 0
HILBERT db 10h dup(0); MATRIZ DONDE GUARDAREMOS EL RESULTADO INICIALIZADA CON 16 0'S
AMPERE db 10h dup(1); MATRIZ 1 CON 16 1'S
BIOSAVAT db 10h dup(2); MATRIZ 2 CON 16 2'S
FOURIER db 10h dup(3); MATRIZ 3 CON 16 3'S
LAPLACE db 10h dup(4); MATRIZ 4 CON 16 4'S
NEWTON db 10h dup(5); MATRIZ 5 CON 16 5'S
ARISTOTELES db 10h dup(6); MATRIZ 6 CON 16 6'S
EINSTEIN db 10h dup(7); MATRIZ 7 CON 16 7'S
PASCAL db 10h dup(8); MATRIZ 8 CON 16 8'S
LEIBNITZ db 10h dup(9); MATRIZ 9 CON 16 9'S
codeseg
start:
mov ax,@data
mov ds,ax
lea si,HILBERT; SI APUNTA A LA MATRIZ RESULTANTE
lea bx,AMPERE; BX APUNTA AL PRIMER ELEMENTO DE LA PRIMERA MATRIZ
mov dx,bx; COPIA LA DIRECCION DE MATRIZ AMPERE Y LA GUARDAMOS EN DX
mov cx,10h; CONTADOR INICIALIZADO EN 16 DECIMAL
SUMA:
mov bx,dx;COPIAMOS LA DIRECCION DEL ELEMENTO CORRESPONDIENTE DE LA PRIMERA MATRIZ
xor ax,ax;LIMPIMAOS AL RESGISTRO AX
mov al,[bx];COPIAMOS EL PRIMER ELEMENTO DE AMPERE A LA PARTE BAJA DE AX
add [si],al;USAMOS COMO ACUMULADOR EL PRIMER ELEMENTO DE LA MATRIZ RESULTANTE Y SUMAREMOS EL ELEMENTO ANTERIORMENTE COPIADO
mov al,[bx+10h];m2; NOS MOVEMOS AL ELEMENTO CORRESPONDIENTE DE LA SIGUIENTE MATRIZ
add [si],al; HACEMOS LO MISMO QUE EN LA INSTRUCCION ADD ANTERIOR PARA SUMAR LAS 9 MATRICES
mov al,[bx+20h];m3
add [si],al
mov al,[bx+30h];m4
add [si],al
mov al,[bx+40h];m5
add [si],al
mov al,[bx+50h];m6
add [si],al
mov al,[bx+60h];m7
add [si],al
mov al,[bx+70h];m8
add [si],al
mov al,[bx+80h];m9
add [si],al
inc si; SI APUNTA AL SIGUIENTE ELEMENTO DE LA MATRIZ RESULTANTE HILBERT
inc dx; AUMENTAMOS DI PARA QUE BX APUNTE AL SIGUIENTE ELEMENTO DE LA 1RA MATRIZ
loop SUMA
exit:
mov ah,04ch
mov al,[exCode]
int 21h
end start
