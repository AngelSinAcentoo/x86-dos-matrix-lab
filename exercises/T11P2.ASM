title PROGRAMA PARA EVALUAR UNA SUMATORIA
model small
stack 256
dataseg
exCode db 0
X db 01h,02h,03h,04h; DEFINIENDO VECTOR X
H db 0,10h,11h,12h,13h; DEFINIENDO VECTOR H
Y dw 0,0,0,0; DEFINIENDO VECTOR DEL RESULTADO DE LA SUMATORIA
codeseg
start:
mov ax,@data
mov ds,ax
lea bx,X; APUNTA AL PRIMER ELEMENTO DE "X"
lea di,H; APUNTA AL PRIMER ELEMENTO DE "H"
lea si,Y; APUNTA AL PRIMER ELEMENTO DE "Y"
mov cx,04h; DEFINIENDO CONTADOR
xor dx,dx; DEFINIENDO ACUMULADOR en 0
Sumatoria:; ETIQUETA DE LA ITERACIÓN
xor ax,ax;LIMPIA AX=0
mov al,[bx]; AL=PRIMER ELEMENTO DE "X"
mul byte ptr [di]; AX=AL*DI (PRIMER ELEMENTO DE X POR EL PRIMERO DE H)
add word ptr [si],ax; COPIA EL RESULTADO DE AX Y LO MANDA A LOS 2 PRIMEROS BYTES DE "Y"
add word ptr [si],dx;; ACUMULA EL RESULTADO DE LA SUMATORIA EN ESA ITERACION
add dx, ax; COPIA EL RESULTADO ACUMULADO Y LO MANDA AL SIGUIENTE ELEMENTO "Y"
inc bx; APUNTA AL SIGUIENTE ELEMENTO DE "X"
inc di; APUNTA AL SIGUIENTE ELEMENTO DE "H"
add si,2; APUNTA AL SIGUIENTE ELEMENTO DE Y
loop Sumatoria; REGRESA A LA ETIQUETA PARA HACER LA ITERACION DEL CODIGO DENTRO DE LA MISMA
int 20h
exit:
mov ah,04ch
mov al,[exCode]
int 21h
end start
